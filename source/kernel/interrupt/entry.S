.intel_syntax noprefix // 使用intel格式汇编语言


.macro TRAP_ENTRY_ERRORCODE n         
.GLOBAL interrupt_handler\n
interrupt_handler\n:
    CLI
    NOP
    PUSH \n
    JMP save_all_registers
.endm

.macro TRAP_ENTRY_NOERRORCODE n         
.GLOBAL interrupt_handler\n
interrupt_handler\n:
    CLI
    PUSH 0
    PUSH \n
    JMP save_all_registers
.endm

.macro INTERRUPT_ENTRY n                
.GLOBAL interrupt_handler\n
.section .text
interrupt_handler\n:
    CLI
    PUSH 0
    PUSH \n
    JMP save_all_registers
.endm
.section .text
 
.GLOBAL save_all_registers
save_all_registers:
    PUSH R15
    PUSH R14
    PUSH R13
    PUSH R12
    PUSH R11
    PUSH R10
    PUSH R9
    PUSH R8
    PUSH RDI
    PUSH RSI
    PUSH RBP
    PUSH RDX
    PUSH RCX
    PUSH RBX
    PUSH RAX 
    MOV  RAX, GS
    PUSH RAX
    MOV  RAX, FS
    PUSH RAX
    MOV  RAX, ES
    PUSH RAX
    MOV  RAX, DS
    PUSH RAX
    MOV  RDI, RSP
    CALL do_IRQ
.GLOBAL return_from_isr
return_from_isr:
    MOV RSP, RAX
    POP RAX
    MOV DS, RAX
    POP RAX
    MOV ES, RAX
    POP RAX
    MOV FS, RAX
    POP RAX
    MOV GS, RAX
    // ignore FS, GS

    POP RAX
    POP RBX
    POP RCX
    POP RDX
    POP RBP
    POP RSI
    POP RDI
    POP R8
    POP R9
    POP R10
    POP R11
    POP R12
    POP R13
    POP R14
    POP R15
    ADD RSP, 16
    IRETQ

ret_from_exception:
    HLT
    JMP ret_from_exception

